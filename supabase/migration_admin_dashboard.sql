ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS suspended BOOLEAN NOT NULL DEFAULT FALSE;

-- Ensure updated_at exists for print job moderation.
ALTER TABLE public.print_jobs
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW();

-- Keep ordinary users from changing their own role/approval fields.
-- The existing RLS policies remain in place; admin mutations are performed
-- only by the protected Vercel API using the server-side service-role key.

-- Recreate the insert policy so suspended users cannot submit jobs.
DROP POLICY IF EXISTS "Approved users can submit own jobs" ON public.print_jobs;
CREATE POLICY "Approved users can submit own jobs"
ON public.print_jobs FOR INSERT TO authenticated
WITH CHECK (
  user_id = (SELECT auth.uid())
  AND status = 'queued'
  AND EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.approved = TRUE
      AND p.suspended = FALSE
  )
);

-- Recreate upload policy so suspended users cannot upload files.
DROP POLICY IF EXISTS "Approved users can upload to own folder" ON storage.objects;
CREATE POLICY "Approved users can upload to own folder"
ON storage.objects FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'print-files'
  AND (storage.foldername(name))[1] = (SELECT auth.uid())::TEXT
  AND EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.approved = TRUE
      AND p.suspended = FALSE
  )
);

